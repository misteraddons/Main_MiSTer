#!/usr/bin/env python3
"""Converts the Define buttons pad drawings in this folder to joymap_pads.h.

Each pad is two uncompressed BMPs:
  <pad>.bmp          1-bit drawing; light palette entries are lit OSD pixels
  <pad>_regions.bmp  8-bit control map; pixel value = PAD_* id + 1 from
                     joymap_pad.h, 0 = no control
On the flash frame a control is drawn solid and the drawing's pixels strictly
inside it (its glyph) are inverted. Output is column bytes per 8-px OSD row,
bit 0 = top, the same layout as logo.h.

Usage: python3 tools/joymap_pads/pad2h.py [output]   (default: joymap_pads.h
at the repository root). --check compares instead of writing.
"""
import argparse
import struct
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parents[1]

# PAD_* order in joymap_pad.h; region value = index + 1.
PAD_IDS = ["PAD_RIGHT", "PAD_LEFT", "PAD_DOWN", "PAD_UP", "PAD_A", "PAD_B", "PAD_X", "PAD_Y", "PAD_L", "PAD_R",
           "PAD_SELECT", "PAD_START", "PAD_L2", "PAD_R2", "PAD_L3", "PAD_R3", "PAD_HOME"]
PADS = ["psx", "snes"]  # JOYMAP_PAD_PSX, JOYMAP_PAD_SNES


def read_bmp(path):
    """Returns (width, height, rows of palette indexes, palette as RGB tuples)."""
    data = path.read_bytes()
    if data[:2] != b"BM":
        raise ValueError(f"{path}: not a BMP")
    offset, header = struct.unpack_from("<II", data, 10)
    width, height, _, bpp, compression = struct.unpack_from("<iiHHI", data, 18)
    if compression or bpp not in (1, 8):
        raise ValueError(f"{path}: need an uncompressed 1-bit or 8-bit BMP")
    colors = struct.unpack_from("<I", data, 46)[0] or (1 << bpp)
    palette = [tuple(data[14 + header + 4 * i + 2 - c] for c in range(3)) for i in range(colors)]
    rows = abs(height)
    stride = (width * bpp + 31) // 32 * 4
    pixels = []
    for r in range(rows):
        line = data[offset + r * stride:offset + (r + 1) * stride]
        if bpp == 8:
            pixels.append(list(line[:width]))
        else:
            pixels.append([(line[x >> 3] >> (7 - (x & 7))) & 1 for x in range(width)])
    if height > 0:
        pixels.reverse()  # bottom-up
    return width, rows, pixels, palette


def load_pad(stem):
    w, h, idx, palette = read_bmp(HERE / f"{stem}.bmp")
    lit = [[sum(palette[i]) > 3 * 127 for i in row] for row in idx]
    rw, rh, regions, _ = read_bmp(HERE / f"{stem}_regions.bmp")
    if (rw, rh) != (w, h):
        raise ValueError(f"{stem}: drawing is {w}x{h} but regions are {rw}x{rh}")
    if h % 8:
        raise ValueError(f"{stem}: height {h} is not whole 8-px OSD rows")
    return w, h, lit, regions


def col_bytes(mask, x0, w, r0, rows):
    out = []
    for r in range(r0, r0 + rows):
        for x in range(x0, x0 + w):
            b = 0
            for n in range(8):
                if mask[r * 8 + n][x]:
                    b |= 1 << n
            out.append(b)
    return out


def hex_lines(values, indent="\t"):
    return [indent + ", ".join(f"0x{v:02X}" for v in values[i:i + 16]) + "," for i in range(0, len(values), 16)]


def pad_source(stem):
    w, h, lit, regions = load_pad(stem)
    out = [f"// {stem}: {w}x{h} px"]
    out.append(f"static const unsigned char joymap_{stem}_pixels[{h // 8} * {w}] = {{")
    out += hex_lines(col_bytes(lit, 0, w, 0, h // 8))
    out.append("};")
    table = []
    for pad_id, name in enumerate(PAD_IDS):
        region = [[v == pad_id + 1 for v in row] for row in regions]
        cells = [(x, y) for y in range(h) for x in range(w) if region[y][x]]
        if not cells:
            continue
        inside = lambda x, y: 0 <= x < w and 0 <= y < h and region[y][x]
        glyph = [[region[y][x] and lit[y][x] and all(inside(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)))
                  for x in range(w)] for y in range(h)]
        x0, x1 = min(c[0] for c in cells), max(c[0] for c in cells)
        r0, r1 = min(c[1] for c in cells) // 8, max(c[1] for c in cells) // 8
        sym = f"joymap_{stem}_{name[4:].lower()}"
        for part, mask in (("fill", region), ("glyph", glyph)):
            out.append(f"static const unsigned char {sym}_{part}[] = {{")
            out += hex_lines(col_bytes(mask, x0, x1 - x0 + 1, r0, r1 - r0 + 1))
            out.append("};")
        table.append(f"\t{{ {name}, {x0}, {x1 - x0 + 1}, {r0}, {r1 - r0 + 1}, {sym}_fill, {sym}_glyph }},")
    out.append(f"static const pad_control joymap_{stem}_controls[] = {{")
    out += table
    out.append("};")
    return out, (w, h // 8, len(table))


def header():
    lines = ["// Generated by tools/joymap_pads/pad2h.py from tools/joymap_pads/*.bmp; do not edit.",
             "#ifndef JOYMAP_PADS_H", "#define JOYMAP_PADS_H", "", "#include \"joymap_pad.h\"", ""]
    entries = []
    for stem in PADS:
        source, (w, rows, count) = pad_source(stem)
        lines += source + [""]
        entries.append(f"\t{{ {w}, {rows}, joymap_{stem}_pixels, joymap_{stem}_controls, {count} }},")
    lines += ["static const pad_bitmap joymap_pads[] = {"] + entries + ["};", "", "#endif", ""]
    return "\n".join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("output", nargs="?", type=Path, default=ROOT / "joymap_pads.h")
    parser.add_argument("--check", action="store_true", help="fail if the output is not up to date")
    args = parser.parse_args()
    text = header()
    if args.check:
        current = args.output.read_text() if args.output.exists() else ""
        if current != text:
            print(f"{args.output} is out of date; run tools/joymap_pads/pad2h.py", file=sys.stderr)
            return 1
        return 0
    args.output.write_text(text, encoding="utf-8", newline="\n")
    return 0


if __name__ == "__main__":
    sys.exit(main())
